"""Migration roundtrip: upgrade → downgrade -1 → upgrade, then zero drift."""
from __future__ import annotations

from pathlib import Path

from sqlalchemy import inspect

PROJECT_ROOT = Path(__file__).resolve().parents[1]
TABLES = {
    "intel_items",
    "intel_approvals",
    "intel_audit_logs",
    "intel_briefing_candidates",
    "intel_reminder_outbox",
}


def _cfg():
    from alembic.config import Config

    cfg = Config(str(PROJECT_ROOT / "alembic.ini"))
    cfg.set_main_option("script_location", str(PROJECT_ROOT / "migrations"))
    return cfg


def test_migration_roundtrip_and_zero_drift():
    from alembic import command

    from app.db import get_engine

    cfg = _cfg()
    engine = get_engine()

    assert TABLES <= set(inspect(engine).get_table_names())

    command.downgrade(cfg, "-1")
    assert not TABLES & set(inspect(engine).get_table_names())

    command.upgrade(cfg, "head")
    assert TABLES <= set(inspect(engine).get_table_names())

    command.check(cfg)  # raises AutogenerateDiffsDetected on any drift